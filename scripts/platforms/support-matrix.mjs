import { readFileSync } from 'node:fs';
import path from 'node:path';
import { parse } from 'yaml';
import { EXPECTED_DIFFERENCES } from './compare-runs.mjs';
import { inside } from './samples.mjs';

const ROOT = path.resolve(import.meta.dirname, '../..');
const START = '<!-- support-matrix:start (generated by npm run gen:checks; do not edit) -->';
const END = '<!-- support-matrix:end -->';
const OS_NAMES = { 'ubuntu-latest': 'Linux', 'macos-latest': 'macOS', 'windows-latest': 'Windows' };
const PLATFORM_NAMES = { linux: 'Linux', darwin: 'macOS', win32: 'Windows' };
const RUNTIME_NAMES = { deno: 'Deno' };

function text(file) {
  return readFileSync(inside(ROOT, file), 'utf8');
}

function workflow(name) {
  return parse(text(`.github/workflows/${name}.yml`));
}

function step(job, action) {
  const found = job.steps.find((candidate) => candidate.uses?.startsWith(`${action}@`));
  if (found === undefined) {
    throw new Error(`No ${action} step in a workflow job the matrix reads`);
  }
  return found.with;
}

function runVersion(job, pattern) {
  const command = job.steps
    .map((candidate) => candidate.run ?? '')
    .find((run) => pattern.test(run));
  return pattern.exec(command ?? '')?.[1] ?? 'not pinned';
}

function pinned(file, name) {
  const line = text(file)
    .split('\n')
    .find((candidate) => candidate.startsWith(`${name}==`));
  return line?.split('==')[1].trim() ?? 'not pinned';
}

function buildPin(file, pattern) {
  return pattern.exec(text(file))?.[1] ?? 'not pinned';
}

function versions(value) {
  return String(value).trim().split(/\s+/u).join(', ');
}

function readSources() {
  const workflows = {
    typescript: workflow('typescript'),
    java: workflow('java-e2e'),
    kotlin: workflow('kotlin-e2e'),
    python: workflow('python-e2e'),
    platforms: workflow('platforms'),
  };
  const manifest = JSON.parse(text('package.json'));
  const samples = workflows.platforms.jobs.samples;
  const runtimes = workflows.platforms.jobs.runtimes;
  return {
    node: step(workflows.typescript.jobs['test-shard'], 'actions/setup-node')['node-version'],
    engines: manifest.engines.node,
    sampleSystems: samples.strategy.matrix.os.map((os) => OS_NAMES[os] ?? os),
    deno: step(runtimes, 'denoland/setup-deno')['deno-version'],
    jdk: step(workflows.java.jobs['java-shard'], 'actions/setup-java')['java-version'],
    gradle: step(workflows.java.jobs['java-shard'], 'gradle/actions/setup-gradle')[
      'gradle-version'
    ],
    kotlinGradle: step(workflows.kotlin.jobs['kotlin-shard'], 'gradle/actions/setup-gradle')[
      'gradle-version'
    ],
    sampleGradle: step(samples, 'gradle/actions/setup-gradle')['gradle-version'],
    python: versions(
      step(workflows.python.jobs['python-shard'], 'actions/setup-python')['python-version'],
    ),
    samplePython: versions(step(samples, 'actions/setup-python')['python-version']),
    poetry: runVersion(workflows.python.jobs['python-shard'], /poetry==(\S+)/u),
    development: manifest.devDependencies,
    junit: buildPin(
      'languages/java/adapters/fixtures/gradle-project/build.gradle',
      /junit-jupiter:([\d.]+)/u,
    ),
    kotlinPlugin: buildPin(
      'languages/java/adapters/fixtures/kotlin-project/build.gradle.kts',
      /kotlin\("jvm"\) version "([^"]+)"/u,
    ),
  };
}

function constraint(name) {
  return pinned('.github/python-e2e-constraints.txt', name);
}

function systemsCell(sources, sampled) {
  const smoke = sources.sampleSystems.filter((name) => name !== 'Linux');
  return sampled ? `Linux (full suite); ${smoke.join(', ')} (sample run)` : 'Linux (full suite)';
}

function presetRows(sources) {
  const node = `Node.js ${String(sources.node)} (needs ${sources.engines})`;
  const vitest = `Vitest ${sources.development.vitest}, Jest ${sources.development.jest}, Mocha ${sources.development.mocha}, \`node:test\``;
  const jdk = `JDK ${String(sources.jdk)} (Temurin)`;
  return [
    [
      'TypeScript',
      systemsCell(sources, true),
      `${node}; Deno ${sources.deno} (sample run)`,
      'npm (pnpm, Yarn and Bun for base installs)',
      vitest,
    ],
    [
      'JavaScript',
      systemsCell(sources, false),
      node,
      'npm (pnpm, Yarn and Bun for base installs)',
      vitest,
    ],
    [
      'Java',
      systemsCell(sources, true),
      `${node}; ${jdk}`,
      `Gradle ${String(sources.gradle)}; Maven from the runner image`,
      `JUnit ${sources.junit}`,
    ],
    [
      'Kotlin',
      systemsCell(sources, false),
      `${node}; ${jdk}; Kotlin ${sources.kotlinPlugin}`,
      `Gradle ${String(sources.kotlinGradle)}`,
      `JUnit 5 through \`kotlin("test")\``,
    ],
    [
      'Python',
      systemsCell(sources, true),
      `${node}; Python ${sources.python} (samples: ${sources.samplePython})`,
      `uv ${constraint('uv')}, Poetry ${sources.poetry}`,
      `pytest ${constraint('pytest')}, nose2 ${constraint('nose2')}, \`unittest\`; coverage ${constraint('coverage')}, mutmut ${constraint('mutmut')}`,
    ],
  ];
}

function tableRow(cells, widths) {
  return `| ${cells.map((cell, index) => cell.padEnd(widths[index])).join(' | ')} |`;
}

function table(header, rows) {
  const widths = header.map((title, column) =>
    Math.max(title.length, ...rows.map((row) => row[column].length)),
  );
  const separator = `| ${widths.map((width) => '-'.repeat(width)).join(' | ')} |`;
  return [tableRow(header, widths), separator, ...rows.map((row) => tableRow(row, widths))].join(
    '\n',
  );
}

function where({ runtime, platform }) {
  return [PLATFORM_NAMES[platform], RUNTIME_NAMES[runtime]].filter(Boolean).join(', ');
}

export function renderSupportMatrix(sources = readSources()) {
  const limits = EXPECTED_DIFFERENCES.map((expected) => [
    where(expected),
    expected.sample,
    expected.tools.map((tool) => `\`${tool}\``).join(', '),
    expected.reason,
  ]);
  return [
    table(
      ['Preset', 'Operating systems', 'Runtimes', 'Build tools', 'Test runners'],
      presetRows(sources),
    ),
    '',
    `The sample runs check these differences from the Linux run under Node.js ${String(sources.node)}; every other finding must match:`,
    '',
    table(['Where', 'Sample', 'Analyzers', 'Why'], limits),
  ].join('\n');
}

export function applySupportMatrix(document) {
  const start = document.indexOf(START);
  const end = document.indexOf(END);
  if (start === -1 || end < start) {
    throw new Error(`docs/compatibility.md must contain the markers ${START} and ${END}`);
  }
  return `${document.slice(0, start + START.length)}\n\n${renderSupportMatrix()}\n\n${document.slice(end)}`;
}
