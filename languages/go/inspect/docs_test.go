const documented = `package cart

// Cart holds the items a shopper picked.
type Cart struct {
	// Items is the items.
	Items []string
	plain int
}

// Total adds up
// the prices.
//
//	total := cart.Total()
//
// Deprecated: use Sum.
func (cart *Cart[T]) Total() int { return 0 }

//go:noinline
//export Hook
func Hook() {}

// Limits.
const (
	// MaxItems is the most items a cart holds.
	MaxItems = 10
	Other    = 2
)

// Reader reads.
var Reader, Writer = 1, 2

// Min, Max.
var Min, Max, _ = 1, 2, 3

/* Block returns the thing the
   caller wants. */
func Block() {}

// Blank is blank.
func _() {}

// Store keeps carts:
//   - in memory
//   - on disk
type Store interface {
	// Load loads.
	Load() error
}
`

func docLine(comment DocComment) string {
	return strings.Join([]string{
		comment.Name, comment.Qualifier, strings.Join(comment.Lines, " / "),
		map[bool]string{true: "detailed", false: ""}[comment.Detailed],
	}, " | ")
}

func TestListsDocCommentsOfDeclarationsWithTheirProse(t *testing.T) {
	report := inspected(t, map[string]string{
		"go.mod":            "module example.com/shop\n",
		"cart/cart.go":      documented,
		"cart/cart_test.go": "package cart\n\n// TestCart tests the cart.\nfunc TestCart() {}\n",
		"cart/gen.go":       "// Code generated by tool. DO NOT EDIT.\n\npackage cart\n\n// Gen gens.\nfunc Gen() {}\n",
	})
	var lines []string
	for _, comment := range report.DocComments {
		lines = append(lines, docLine(comment))
	}
	want := []string{
		"Cart |  | Cart holds the items a shopper picked. | ",
		"Items | Cart.Items | Items is the items. | ",
		"Total | Cart.Total | Total adds up / the prices. | detailed",
		"MaxItems |  | MaxItems is the most items a cart holds. | ",
		"Reader, Writer |  | Reader reads. | ",
		"Min, Max |  | Min, Max. | ",
		"Block |  | Block returns the thing the / caller wants. | ",
		"Store |  | Store keeps carts: / in memory / on disk | ",
		"Load | Store.Load | Load loads. | ",
	}
	if !reflect.DeepEqual(lines, want) {
		t.Fatalf("got\n%s\nwant\n%s", strings.Join(lines, "\n"), strings.Join(want, "\n"))
	}
	if report.DocComments[0].File != "cart/cart.go" || report.DocComments[0].Line != 3 {
		t.Fatalf("first comment: %+v", report.DocComments[0])
	}
}
