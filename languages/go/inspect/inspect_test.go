package main

import (
	"os"
	"path/filepath"
	"testing"
)

func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, text := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func inspected(t *testing.T, files map[string]string) Report {
	t.Helper()
	report, err := inspectModule(writeModule(t, files))
	if err != nil {
		t.Fatal(err)
	}
	return report
}

func functionNamed(t *testing.T, report Report, name string) Function {
	t.Helper()
	for _, function := range report.Functions {
		if function.Name == name {
			return function
		}
	}
	t.Fatalf("no function %s in %+v", name, report.Functions)
	return Function{}
}

const nested = `package demo

func Classify(values []int, limit int, label string) (string, error) {
	for _, value := range values {
		if value > limit {
			if value > 2*limit && label != "" {
				return "far", nil
			} else if value > limit+1 {
				return "near", nil
			}
		}
	}
	switch {
	case limit < 0:
		return "negative", nil
	default:
		return "", nil
	}
}
`

func TestMeasuresFunctionStructure(t *testing.T) {
	report := inspected(t, map[string]string{"go.mod": "module demo\n", "demo.go": nested})
	got := functionNamed(t, report, "Classify")
	want := Function{
		File: "demo.go", Name: "Classify", Start: 3, End: 19, Lines: 17,
		Statements: 9, MaxControlNesting: 3, Parameters: 3, Complexity: 7,
	}
	if got != want {
		t.Fatalf("got %+v, want %+v", got, want)
	}
}

const closures = `package demo

type Store struct{ items, names []string; count int }

func (store *Store) Each(visit func(string)) {
	for _, item := range store.items {
		go func() {
			if item != "" {
				visit(item)
			}
		}()
	}
}

func (store Store) Size() int { return store.count }
`

func TestMeasuresFunctionLiteralsAsTheirOwnUnits(t *testing.T) {
	report := inspected(t, map[string]string{"go.mod": "module demo\n", "store.go": closures})
	outer := functionNamed(t, report, "Store.Each")
	literal := functionNamed(t, report, "Store.Each.func1")
	if outer.MaxControlNesting != 1 || outer.Statements != 2 || outer.Parameters != 1 {
		t.Fatalf("outer: %+v", outer)
	}
	if literal.MaxControlNesting != 1 || literal.Statements != 2 || literal.Start != 7 {
		t.Fatalf("literal: %+v", literal)
	}
	if len(report.Types) != 1 || report.Types[0].Methods != 2 || report.Types[0].Fields != 3 {
		t.Fatalf("types: %+v", report.Types)
	}
}

func TestListsTestsAndSkipsGeneratedAndNestedModules(t *testing.T) {
	report := inspected(t, map[string]string{
		"go.mod":              "module demo\n",
		"demo.go":             "package demo\n\nfunc Value() int { return 1 }\n",
		"demo_test.go":        "package demo\n\nimport \"testing\"\n\nfunc TestValue(t *testing.T) {}\n\nfunc testHelper() {}\n",
		"gen.go":              "// Code generated by tool. DO NOT EDIT.\n\npackage demo\n\nfunc Generated() {}\n",
		"testdata/skip.go":    "package skip\n",
		"tools/go.mod":        "module tools\n",
		"tools/tools.go":      "package tools\n",
		"internal/x/y.go":     "package x\n\ntype Speaker interface{ Speak() string; Close() error }\n",
		".hidden/ignored.go":  "package ignored\n",
		"_scratch/ignored.go": "package ignored\n",
	})
	if len(report.Files) != 4 {
		t.Fatalf("files: %+v", report.Files)
	}
	if len(report.Tests) != 1 || report.Tests[0].Name != "TestValue" {
		t.Fatalf("tests: %+v", report.Tests)
	}
	if len(report.Functions) != 1 || report.Functions[0].Name != "Value" {
		t.Fatalf("functions: %+v", report.Functions)
	}
	if len(report.Types) != 1 || report.Types[0].Kind != "interface" || report.Types[0].Methods != 2 {
		t.Fatalf("types: %+v", report.Types)
	}
}

func TestReportsFilesThatDoNotParse(t *testing.T) {
	report := inspected(t, map[string]string{"go.mod": "module demo\n", "broken.go": "package demo\n\nfunc {\n"})
	if len(report.Errors) == 0 {
		t.Fatal("expected a parse error")
	}
}
