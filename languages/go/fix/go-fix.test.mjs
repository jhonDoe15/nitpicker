import { readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { fixtureGit, useGitFixtures } from '../../../core/diff/git/test-support/git-repository.mjs';
import { writeFiles } from '../../../core/diff/git/test-support/fixture-files.mjs';
import { fixWorkingTree } from '../../../core/fix/run-fix.mjs';
import { FAKE_GOFMT, fakeGoFormat } from './test-support/fake-go-format.mjs';

const { createGitRepository, temporaryRoot } = useGitFixtures();
const GO_MOD = 'module example.com/shop\n\ngo 1.24\n';

function topic(base, changes) {
  const repository = createGitRepository({ 'go.mod': GO_MOD, ...base }, { baseRef: 'base' });
  fixtureGit(repository.root, ['checkout', '-q', '-b', 'topic']);
  writeFiles(repository.root, changes);
  return repository;
}

function fix(repository, tools, headPolicy = {}) {
  return fixWorkingTree({
    repositoryRoot: repository.root,
    projectRoot: repository.root,
    baseRef: 'base',
    executeFixCommand: tools.executeFixCommand,
    spawnEnvironment: { XDG_CACHE_HOME: temporaryRoot('nitpicker-go-fix-cache-') },
    headPolicy: { exclude: [], conventions: {}, ...headPolicy },
    config: { preset: 'go' },
  });
}

function read(repository, name) {
  return readFileSync(path.join(repository.root, name), 'utf8');
}

describe('--fix for Go', () => {
  it('formats the changed Go files and leaves a file unformatted on the base as it is', () => {
    const repository = topic(
      { 'a.go': 'package a\n', 'legacy.go': 'package  a\n', 'same.go': 'package  a\n' },
      {
        'a.go': 'package  a\n',
        'legacy.go': 'package  a\n\nvar  x = 1\n',
        'b/b.go': 'package  b\n',
      },
    );
    const tools = fakeGoFormat();

    const result = fix(repository, tools);

    expect(result).toEqual({
      fixedFiles: ['a.go', 'b/b.go'],
      toolErrors: [],
      notes: [
        'gofmt rewrote a.go, b/b.go',
        'gofmt left legacy.go as is: already unformatted before your change',
      ],
    });
    expect(
      ['a.go', 'b/b.go', 'legacy.go', 'same.go'].map((name) => read(repository, name)),
    ).toEqual(['package a\n', 'package b\n', 'package  a\n\nvar  x = 1\n', 'package  a\n']);
  });
  it('runs the formatter from the project root through standard input, goimports with the file as its source', () => {
    const repository = topic(
      { 'go.mod': `${GO_MOD}\ntool golang.org/x/tools/cmd/goimports\n` },
      { 'b/b.go': 'package  b\n' },
    );
    const tools = fakeGoFormat();

    fix(repository, tools);

    expect(
      tools
        .formatterCalls()
        .map(({ command, args, cwd, input }) => ({ command, args, cwd, input })),
    ).toEqual([
      {
        command: 'go',
        args: [
          'tool',
          'golang.org/x/tools/cmd/goimports',
          '-srcdir',
          path.join(repository.root, 'b/b.go'),
        ],
        cwd: repository.root,
        input: 'package  b\n',
      },
    ]);
  });
  it('writes the formatter output with its own line endings, as the format check expects', () => {
    const repository = topic({}, { 'a.go': 'package a\r\n' });

    const result = fix(repository, fakeGoFormat());

    expect([result.fixedFiles, read(repository, 'a.go')]).toEqual([['a.go'], 'package a\n']);
  });
  it('names a file the formatter cannot parse and leaves it as it is', () => {
    const repository = topic({}, { 'a.go': 'package  a\nBROKEN\n' });

    const result = fix(repository, fakeGoFormat());

    expect(result).toEqual({
      fixedFiles: [],
      toolErrors: [],
      notes: ['gofmt could not parse a.go'],
    });
  });
  it('reports a formatter that fails as a tool error and writes nothing', () => {
    const repository = topic({}, { 'a.go': 'package  a\n' });
    const tools = fakeGoFormat({
      formatterReply: { status: 1, stdout: '', stderr: 'gofmt broke' },
    });

    const result = fix(repository, tools);

    expect([result.fixedFiles, result.toolErrors.map(({ tool, rule }) => [tool, rule])]).toEqual([
      [],
      [['go-format-fix', 'fix-failed']],
    ]);
    expect(result.toolErrors[0].message).toBe(
      `${FAKE_GOFMT} exited 1:\ngofmt broke\nSee https://github.com/jhonDoe15/nitpicker/blob/main/docs/troubleshooting.md#fixers-fail`,
    );
    expect(read(repository, 'a.go')).toBe('package  a\n');
  });
  it('leaves generated, excluded and non-Go files to themselves', () => {
    const repository = topic(
      {},
      {
        'gen.go': '// Code generated by stringer. DO NOT EDIT.\n\npackage  a\n',
        'vendor/v.go': 'package  v\n',
        'notes.md': 'a  b\n',
      },
    );
    const tools = fakeGoFormat();

    const result = fix(repository, tools, { exclude: ['vendor/**'] });

    expect([result, tools.formatterCalls()]).toEqual([
      { fixedFiles: [], toolErrors: [], notes: [] },
      [],
    ]);
  });
});
