import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { isGeneratedJvm, withoutGeneratedSources } from './generated-sources.mjs';

const roots = [];

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

function project(files) {
  const root = realpathSync(mkdtempSync(path.join(tmpdir(), 'nitpicker-generated-jvm-')));
  roots.push(root);
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    writeFileSync(path.join(root, file), text);
  }
  return root;
}

const PROTO =
  '// Generated by the protocol buffer compiler.  DO NOT EDIT!\npackage shop;\nclass Order {}\n';

describe('isGeneratedJvm', () => {
  it('knows a source with the header or annotation of a known generator', () => {
    const root = project({
      'src/main/java/shop/Order.java': PROTO,
      'src/main/java/shop/Tables.java':
        '/*\n * This file is generated by jOOQ.\n */\npackage shop;\nclass Tables {}\n',
      'src/main/java/shop/OrderMapperImpl.java':
        'package shop;\n\nimport javax.annotation.processing.Generated;\n\n@Generated(value = "org.mapstruct.ap.MappingProcessor")\nclass OrderMapperImpl {}\n',
      'src/main/kotlin/shop/Api.kt':
        '// Code generated by Wire protocol buffer compiler, do not edit.\npackage shop\n',
    });

    expect(
      [
        'src/main/java/shop/Order.java',
        'src/main/java/shop/Tables.java',
        'src/main/java/shop/OrderMapperImpl.java',
        'src/main/kotlin/shop/Api.kt',
      ].map((file) => isGeneratedJvm(root, file)),
    ).toEqual([true, true, true, true]);
  });

  it('knows the build tools generated-source folders, and a generic marker only in a generated-looking folder', () => {
    const root = project({
      'build/generated/sources/annotationProcessor/java/main/shop/A.java':
        'package shop;\nclass A {}\n',
      'build/generated/ksp/main/kotlin/shop/B.kt': 'package shop\nclass B\n',
      'target/generated-sources/delombok/shop/C.java': 'package shop;\nclass C {}\n',
      'src/main/generated/shop/D.java': '// @generated\npackage shop;\nclass D {}\n',
      'src/main/java/shop/E.java': '// @generated\npackage shop;\nclass E {}\n',
      'src/main/java/shop/F.java': '// DO NOT EDIT\npackage shop;\nclass F {}\n',
    });

    expect(
      [
        'build/generated/sources/annotationProcessor/java/main/shop/A.java',
        'build/generated/ksp/main/kotlin/shop/B.kt',
        'target/generated-sources/delombok/shop/C.java',
        'src/main/generated/shop/D.java',
        'src/main/java/shop/E.java',
        'src/main/java/shop/F.java',
      ].map((file) => isGeneratedJvm(root, file)),
    ).toEqual([true, true, true, true, false, false]);
  });

  it('does not take hand-written code, a header below the code, a missing file or a build file', () => {
    const root = project({
      'src/main/java/shop/Hand.java':
        'package shop;\n// Generated by the protocol buffer compiler.  DO NOT EDIT!\nclass Hand {}\n',
      'pom.xml': '<!-- Generated by the protocol buffer compiler.  DO NOT EDIT! -->\n',
    });

    expect(
      ['src/main/java/shop/Hand.java', 'src/main/java/shop/Gone.java', 'pom.xml'].map((file) =>
        isGeneratedJvm(root, file),
      ),
    ).toEqual([false, false, false]);
  });
});

describe('withoutGeneratedSources', () => {
  it('drops the findings on generated sources and keeps the rest, tool errors included', () => {
    const root = project({
      'src/main/java/shop/Order.java': PROTO,
      'src/main/java/shop/Hand.java': 'package shop;\nclass Hand {}\n',
    });
    const findings = [
      { path: 'src/main/java/shop/Order.java', rule: 'a' },
      { path: 'src/main/java/shop/Hand.java', rule: 'b' },
      { path: '.', rule: 'gradle-failure' },
    ];

    expect(withoutGeneratedSources(findings, root).map(({ rule }) => rule)).toEqual([
      'b',
      'gradle-failure',
    ]);
  });
});
