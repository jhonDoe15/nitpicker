import { describe, expect, it } from 'vitest';
import { lineOf, scanKotlinSource } from '../kotlin-source.mjs';
import { annotationMarkers, commentedOutCode, generatedFile } from './markers.mjs';

function found(check, source) {
  const scanned = scanKotlinSource(source);
  return check(scanned).map((reported) => [reported.rule, lineOf(scanned, reported.offset)]);
}

describe('annotationMarkers', () => {
  it.each([
    ['@Generated', 'GeneratedOnHandWrittenCode'],
    ['@javax.annotation.processing.Generated("x")', 'GeneratedOnHandWrittenCode'],
    ['@lombok.Generated', 'GeneratedOnHandWrittenCode'],
    ['@DoNotMutate', 'MutationIgnoreMarker'],
    ['@com.arcmutate.DoNotMutate', 'MutationIgnoreMarker'],
    ['@CoverageIgnore', 'MutationIgnoreMarker'],
  ])('flags %s on hand-written code', (annotation, rule) => {
    expect(found(annotationMarkers, `${annotation}\nfun keep() = 1\n`)).toEqual([[rule, 1]]);
  });

  it.each([
    ['a class', '@Generated(value = ["gen"])\n@JvmInline\nvalue class Id(val raw: Long)\n'],
    ['a data class behind modifiers', '@Generated internal data class Order(val id: Long)\n'],
    ['an object', '@Generated\nobject Registry\n'],
    ['a function', '@Generated\n@JvmStatic\nprivate suspend fun load() = 1\n'],
    ['a constructor', 'class Order @Generated constructor(val id: Long)\n'],
    ['a getter', 'class Order {\n  @get:Generated\n  val id: Long = 1\n}\n'],
  ])('flags @Generated on %s', (_name, source) => {
    expect(found(annotationMarkers, source).map(([rule]) => rule)).toEqual([
      'GeneratedOnHandWrittenCode',
    ]);
  });

  it('passes JPA and Hibernate generated values on properties and other names that contain Generated', () => {
    const source = [
      '@Entity',
      'class Order(',
      '  @Id @GeneratedValue(strategy = GenerationType.IDENTITY)',
      '  val id: Long? = null,',
      '  @org.hibernate.annotations.Generated val version: Long = 0,',
      '  @CreationTimestamp val createdAt: Instant? = null,',
      ') {',
      '  @Generated',
      '  var total: Long = 0',
      '}',
      '@file:Generated',
      '@ExcludeFromGeneratedReport',
      'fun keep() = 1',
    ].join('\n');

    expect(found(annotationMarkers, source)).toEqual([]);
  });

  it('passes other annotations and markers in comments or strings', () => {
    const source =
      '@JvmStatic\n// @Generated\nval text = "@DoNotMutate"\n@Suppress("unused")\nfun keep() = 1\n';

    expect(found(annotationMarkers, source)).toEqual([]);
  });
});

describe('generatedFile', () => {
  it.each([
    ['an @generated header', '// @generated by protoc\npackage demo\n'],
    ['a do-not-edit header', '/*\n * Generated by the build. Do not edit.\n */\npackage demo\n'],
    [
      'a generator header after a license comment',
      '// Copyright the authors\n\n// Code generated by sqlc. DO NOT EDIT.\npackage demo\n',
    ],
  ])('knows %s marks a generated file', (_name, source) => {
    expect(generatedFile(scanKotlinSource(source))).toBe(true);
  });

  it('does not take a comment after code, or one that mentions generation, as the header', () => {
    expect(generatedFile(scanKotlinSource('package demo\n// @generated\n'))).toBe(false);
    expect(generatedFile(scanKotlinSource('// Builds the generated report.\npackage demo\n'))).toBe(
      false,
    );
  });
});

describe('commentedOutCode', () => {
  it.each([
    ['a declaration', '// val total = compute(items)'],
    ['a call', '// repository.save(order)'],
    ['an assignment', '// this.total += item.price'],
    ['a control header', '// if (order.isPaid()) {'],
    ['a function', '// private fun total(): Int = 1'],
    ['a class', '// data class Order(val id: Int) {'],
    ['an import', '// import kotlin.math.max'],
    ['a return', '// return null'],
    ['a block comment', '/* val total = compute(items) */'],
  ])('flags %s', (_name, comment) => {
    expect(found(commentedOutCode, `fun f() {\n    ${comment}\n}\n`)).toEqual([
      ['CommentedOutCode', 2],
    ]);
  });

  it('reports a run of commented lines once', () => {
    const source = 'fun f() {\n    // val a = 1\n    // val b = 2\n\n    // val c = 3\n}\n';

    expect(found(commentedOutCode, source)).toEqual([
      ['CommentedOutCode', 2],
      ['CommentedOutCode', 5],
    ]);
  });

  it.each([
    ['prose', '// Keep the total in cents so rounding stays exact.'],
    ['prose that mentions a call', '// Callers must check isPaid() first.'],
    ['a KDoc sample', '/**\n * val total = compute(items)\n */'],
    ['a fenced sample', '/*\n * ```\n * val total = compute(items)\n * ```\n */'],
    ['a link', '// https://example.com/docs(1)'],
    ['a TODO', '// TODO(#12): call(x)'],
    ['a list item', '// - total(items)'],
  ])('passes %s', (_name, comment) => {
    expect(found(commentedOutCode, `${comment}\nfun f() = 1\n`)).toEqual([]);
  });
});
