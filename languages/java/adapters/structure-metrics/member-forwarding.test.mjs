import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterAll, beforeAll, expect, it } from 'vitest';
import { compiledMetrics, runMetrics } from './test-support/compiled-metrics.mjs';
import { JAVA_ALIASES } from './test-support/forwarding-sources.mjs';
import { readJavaMemberAliases } from '../review-rules/forwarding/alias-findings.mjs';
import { withoutGeneratedSources } from '../generated/generated-sources.mjs';
import { compareFindings } from '../../../../core/diff/comparison/compare.mjs';

let root;
let classes;
const file = 'src/Aliases.java';

beforeAll(() => {
  root = mkdtempSync(path.join(tmpdir(), 'nitpicker-member-aliases-'));
  mkdirSync(path.join(root, 'src'));
  classes = compiledMetrics();
});

afterAll(() => {
  rmSync(root, { recursive: true, force: true });
});

function collect(source) {
  writeFileSync(path.join(root, file), source);
  const output = path.join(root, 'structure.json');
  const classReport = path.join(root, 'classes.json');
  const result = runMetrics(classes, { cwd: root, args: [output, classReport, root, 'src'] });
  if (result.status !== 0) {
    throw new Error(result.stderr);
  }
  return readJavaMemberAliases({ reportRoot: root, manifest: { sourceRoots: ['src'] } });
}

it('uses the real Java parser to report same-contract aliases and spare contract boundaries', () => {
  const findings = collect(JAVA_ALIASES);

  expect(findings.map(({ symbol }) => symbol)).toEqual([
    'Aliases.alias',
    'Aliases.explicit',
    'Aliases.passVoid',
    'Aliases.zero',
  ]);
});

it('keeps identities across inserted lines and honors generated-source exclusion', () => {
  const baseFindings = collect(JAVA_ALIASES);
  const headFindings = collect(`\n\n${JAVA_ALIASES}`);

  expect(compareFindings({ baseFindings, headFindings }).newFindings).toEqual([]);
  expect(headFindings.map(({ location }) => location.line)).toEqual(
    baseFindings.map(({ location }) => location.line + 2),
  );
  writeFileSync(path.join(root, file), `// Code generated by sqlc. DO NOT EDIT.\n${JAVA_ALIASES}`);
  expect(withoutGeneratedSources(headFindings, root)).toEqual([]);
  expect(JSON.parse(readFileSync(path.join(root, 'classes.json'), 'utf8')).forwarders).toHaveLength(
    4,
  );
});
