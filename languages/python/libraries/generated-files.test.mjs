import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { dropGeneratedFindings } from './generated-files.mjs';

const roots = [];

function project(files) {
  const root = mkdtempSync(path.join(tmpdir(), 'generated-files-'));
  roots.push(root);
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    writeFileSync(path.join(root, file), text);
  }
  return root;
}

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

const finding = (rule, file) => ({ rule, path: file, subject: 'Cart.total', line: 5 });

describe('dropGeneratedFindings', () => {
  it('drops only the named rules in generated files', () => {
    const root = project({
      'src/cart.py': 'class Cart:\n    pass\n',
      'src/orders_pb2.py': 'class Orders:\n    pass\n',
      'src/models.py':
        '# Generated by the protocol buffer compiler.  DO NOT EDIT!\nclass M:\n    pass\n',
    });
    const findings = [
      finding('forwarding-method-alias', 'src/cart.py'),
      finding('forwarding-method-alias', 'src/orders_pb2.py'),
      finding('forwarding-method-alias', 'src/models.py'),
      finding('other-rule', 'src/orders_pb2.py'),
    ];

    expect(dropGeneratedFindings(findings, root, ['forwarding-method-alias'])).toEqual([
      finding('forwarding-method-alias', 'src/cart.py'),
      finding('other-rule', 'src/orders_pb2.py'),
    ]);
  });
});
