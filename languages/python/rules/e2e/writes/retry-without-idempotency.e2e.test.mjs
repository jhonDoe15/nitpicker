import { afterEach, describe, expect, it } from 'vitest';
import { createScripts } from '../../test-support/python-script-helpers.mjs';

const enabled = process.env.NITPICKER_PYTHON_E2E === '1';
const { cleanup, outcomes } = createScripts({ hidden: ['swallowed-exception'] });
afterEach(cleanup);

const code = (...lines) => `${lines.join('\n')}\n`;

describe.skipIf(!enabled)('retry-without-idempotency', () => {
  it('flags a payment, message or insert that a retry can run twice', () => {
    const [actual, expected] = outcomes([
      [
        'a tenacity decorator around a Stripe create',
        code(
          'import stripe',
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def charge(amount):',
          '    return stripe.PaymentIntent.create(amount=amount, currency="usd")',
        ),
        ['retry-without-idempotency:7 stripe.PaymentIntent.create()|payment|@retry'],
      ],
      [
        'a Stripe create with an idempotency key',
        code(
          'import stripe',
          'from tenacity import retry',
          '',
          '',
          '@retry(stop=3)',
          'def charge(amount, key):',
          '    return stripe.PaymentIntent.create(amount=amount, idempotency_key=key)',
        ),
        [],
      ],
      [
        'a backoff decorator around a Kafka send',
        code(
          'import backoff',
          'from kafka import KafkaProducer',
          '',
          'producer = KafkaProducer()',
          '',
          '',
          '@backoff.on_exception(backoff.expo, OSError)',
          'def publish(event):',
          '    producer.send("events", event)',
        ),
        ['retry-without-idempotency:9 producer.send()|message|@on_exception'],
      ],
      [
        'an SQS send without a deduplication id',
        code(
          'import boto3',
          'import stamina',
          '',
          'queue = boto3.client("sqs")',
          '',
          '',
          '@stamina.retry(on=OSError)',
          'def publish(body):',
          '    queue.send_message(QueueUrl="u", MessageBody=body)',
        ),
        ['retry-without-idempotency:9 queue.send_message()|message|@retry'],
      ],
      [
        'an SQS FIFO send with a deduplication id',
        code(
          'import boto3',
          'import stamina',
          '',
          'queue = boto3.client("sqs")',
          '',
          '',
          '@stamina.retry(on=OSError)',
          'def publish(body, key):',
          '    queue.send_message(QueueUrl="u", MessageBody=body, MessageDeduplicationId=key)',
        ),
        [],
      ],
      [
        'a Celery task enqueue',
        code(
          'from celery import shared_task',
          'from tenacity import retry',
          '',
          '',
          '@shared_task',
          'def notify(order_id):',
          '    return order_id',
          '',
          '',
          '@retry',
          'def enqueue(order_id):',
          '    notify.delay(order_id)',
        ),
        ['retry-without-idempotency:12 notify.delay()|message|@retry'],
      ],
      [
        'an insert in a retried function',
        code(
          'from retrying import retry',
          '',
          '',
          '@retry',
          'def store(cursor, row):',
          '    cursor.execute("INSERT INTO orders (id) VALUES (%s)", (row,))',
        ),
        ['retry-without-idempotency:6 cursor.execute()|insert|@retry'],
      ],
      [
        'an insert with ON CONFLICT',
        code(
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def store(cursor, row):',
          '    cursor.execute("INSERT INTO orders (id) VALUES (%s) ON CONFLICT DO NOTHING", (row,))',
        ),
        [],
      ],
      [
        'an insert with ON DUPLICATE KEY UPDATE',
        code(
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def store(cursor, row):',
          '    cursor.execute("insert into orders (id) values (%s) on duplicate key update id = id", (row,))',
        ),
        [],
      ],
      [
        'a SQLAlchemy insert construct',
        code(
          'from sqlalchemy import insert',
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def store(session, row):',
          '    session.execute(insert(Order).values(row))',
        ),
        ['retry-without-idempotency:7 session.execute()|insert|@retry'],
      ],
      [
        'a SQLAlchemy insert with an upsert',
        code(
          'from sqlalchemy.dialects.postgresql import insert',
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def store(session, row):',
          '    session.execute(insert(Order).values(row).on_conflict_do_nothing())',
        ),
        [],
      ],
      [
        'a select in a retry',
        code(
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def load(cursor, row):',
          '    cursor.execute("SELECT * FROM orders WHERE id = %s", (row,))',
        ),
        [],
      ],
      [
        'an HTTP post in a retry',
        code(
          'import requests',
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def call(url):',
          '    return requests.post(url, timeout=5)',
        ),
        [],
      ],
      [
        'an unknown write in a retry',
        code(
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def call(client):',
          '    return client.submit({"id": 1})',
        ),
        [],
      ],
      [
        'a helper that publishes',
        code(
          'from kafka import KafkaProducer',
          'from tenacity import retry',
          '',
          'producer = KafkaProducer()',
          '',
          '',
          'def emit(event):',
          '    producer.send("events", event)',
          '',
          '',
          '@retry',
          'def publish(event):',
          '    emit(event)',
        ),
        ['retry-without-idempotency:13 emit() > producer.send()|message|@retry'],
      ],
      [
        'a Retrying loop',
        code(
          'from kafka import KafkaProducer',
          'from tenacity import Retrying',
          '',
          'producer = KafkaProducer()',
          '',
          '',
          'def publish(event):',
          '    for attempt in Retrying():',
          '        with attempt:',
          '            producer.send("events", event)',
        ),
        ['retry-without-idempotency:10 producer.send()|message|Retrying'],
      ],
      [
        'a Retrying call of a function',
        code(
          'from kafka import KafkaProducer',
          'from tenacity import Retrying',
          '',
          'producer = KafkaProducer()',
          '',
          '',
          'def emit(event):',
          '    producer.send("events", event)',
          '',
          '',
          'def publish(event):',
          '    Retrying()(emit, event)',
        ),
        ['retry-without-idempotency:12 emit() > producer.send()|message|Retrying'],
      ],
      [
        'a hand-written retry loop',
        code(
          'from kafka import KafkaProducer',
          '',
          'producer = KafkaProducer()',
          '',
          '',
          'def publish(event):',
          '    for attempt in range(3):',
          '        try:',
          '            producer.send("events", event)',
          '            return',
          '        except OSError:',
          '            continue',
        ),
        ['retry-without-idempotency:9 producer.send()|message|retry loop'],
      ],
      [
        'a write outside any retry',
        code(
          'from kafka import KafkaProducer',
          '',
          'producer = KafkaProducer()',
          '',
          '',
          'def publish(event):',
          '    producer.send("events", event)',
        ),
        [],
      ],
      [
        'only the read is retried',
        code(
          'import stripe',
          'from tenacity import retry',
          '',
          '',
          '@retry',
          'def quote(ident):',
          '    return stripe.PaymentIntent.retrieve(ident)',
        ),
        [],
      ],
    ]);
    expect(actual).toEqual(expected);
  });
});
