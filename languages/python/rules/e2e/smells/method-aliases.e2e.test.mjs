import { afterEach, describe, expect, it } from 'vitest';
import { createScripts } from '../../test-support/python-script-helpers.mjs';
import { ingestRulesReport } from '../../../ingest/rules-report.mjs';
import { compareFindings } from '../../../../../core/diff/comparison/compare.mjs';

const enabled = process.env.NITPICKER_PYTHON_E2E === '1';
const { cleanup, outcomes, findingsOf } = createScripts();
afterEach(cleanup);

const source = `class Price:
    def target(self, value: int) -> int:
        return value + 1
    def alias(self, value: int) -> int:
        return self.target(value)
`;

function changed(before, after) {
  return source.replace(before, after);
}

describe.skipIf(!enabled)('same-class Python method aliases', () => {
  it('reports unchanged contracts and preserves adaptation, callbacks and compatibility', () => {
    const [actual, expected] = outcomes([
      ['plain', source, ['forwarding-method-alias:4 Price.alias -> Price.target']],
      [
        'nested owner',
        `class Outer:\n${source
          .split('\n')
          .map((line) => `    ${line}`)
          .join('\n')}`,
        ['forwarding-method-alias:5 Outer.Price.alias -> Outer.Price.target'],
      ],
      [
        'zero arguments',
        source
          .replaceAll('self, value: int', 'self')
          .replace('value + 1', '1')
          .replace('self.target(value)', 'self.target()'),
        ['forwarding-method-alias:4 Price.alias -> Price.target'],
      ],
      [
        'keyword only',
        source
          .replaceAll('self, value: int', 'self, *, value: int')
          .replace('self.target(value)', 'self.target(value=value)'),
        ['forwarding-method-alias:4 Price.alias -> Price.target'],
      ],
      ['changed argument', changed('self.target(value)', 'self.target(value + 1)'), []],
      [
        'return adaptation',
        changed('def alias(self, value: int) -> int:', 'def alias(self, value: int) -> float:'),
        [],
      ],
      ['annotation absent', changed('value: int', 'value'), []],
      ['inherited', changed('class Price:', 'class Price(Base):'), []],
      ['decorated', changed('    def alias', '    @override\n    def alias'), []],
      ['factory', changed('def alias', 'def of'), []],
      ['different receiver', changed('self.target(value)', 'other.target(value)'), []],
      ['default', changed('def alias(self, value: int)', 'def alias(self, value: int = 1)'), []],
      ['async', changed('def alias', 'async def alias'), []],
      [
        'callback field',
        changed(
          'class Price:',
          'class Price:\n    def __init__(self, callback):\n        self.target = callback',
        ),
        [],
      ],
      ['unresolved target', changed('self.target(value)', 'self.missing(value)'), []],
      ['decorated class', `@dataclass(frozen=True)\n${source}`, []],
    ]);

    expect(actual).toEqual(expected);
  });

  it('keeps actual reported subjects stable when lines move and skips generated files', () => {
    const before = findingsOf({ 'src/prices.py': source }).filter((item) =>
      item.startsWith('forwarding-method-alias '),
    );
    const after = findingsOf({ 'src/prices.py': `\n\n${source}` }).filter((item) =>
      item.startsWith('forwarding-method-alias '),
    );
    const raw = {
      rule: 'forwarding-method-alias',
      path: 'src/prices.py',
      subject: 'Price.alias -> Price.target',
      line: 4,
    };

    expect(before).toEqual(['forwarding-method-alias src/prices.py:4 Price.alias -> Price.target']);
    expect(after).toEqual(['forwarding-method-alias src/prices.py:6 Price.alias -> Price.target']);
    expect(
      compareFindings({
        baseFindings: ingestRulesReport(JSON.stringify([raw])),
        headFindings: ingestRulesReport(JSON.stringify([{ ...raw, line: 6 }])),
      }).newFindings,
    ).toEqual([]);
    expect(
      findingsOf({ 'src/prices.py': `# Code generated by sqlc. DO NOT EDIT.\n${source}` }).filter(
        (item) => item.startsWith('forwarding-method-alias '),
      ),
    ).toEqual([]);
  });
});
