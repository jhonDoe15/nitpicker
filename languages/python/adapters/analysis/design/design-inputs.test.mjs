import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { designFiles } from './design-files.mjs';
import { designDistributions } from './design-distributions.mjs';

const roots = [];

afterEach(() => {
  for (const root of roots.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

function project(files) {
  const root = realpathSync(mkdtempSync(path.join(tmpdir(), 'nitpicker-python-design-')));
  roots.push(root);
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    writeFileSync(path.join(root, file), text);
  }
  return root;
}

const DISTRIBUTION = '[project]\nname = "x"\n[build-system]\nbuild-backend = "hatchling.build"\n';

describe('choosing the files the design facts cover', () => {
  const files = {
    'app/__init__.py': '',
    'app/core.py': 'x = 1\n',
    'app/skipped.py': 'x = 1\n',
    'app/api_pb2.py': 'x = 1\n',
    'app/models.py': '# Code generated by tool. DO NOT EDIT.\nx = 1\n',
    'lib/run.py': 'x = 1\n',
  };

  it('keeps the listed files inside the source roots that are neither excluded nor generated', () => {
    const projectRoot = project(files);
    const sources = Object.keys(files).sort();

    expect(
      designFiles(
        { projectRoot, project: { sourceRoots: ['app'] }, exclude: ['app/skipped.py'] },
        sources,
      ),
    ).toEqual(['app/__init__.py', 'app/core.py']);
  });

  it('keeps every listed file of the whole project when no exclusion applies', () => {
    const projectRoot = project(files);

    expect(
      designFiles({ projectRoot, project: { sourceRoots: ['.'] } }, ['app/core.py', 'lib/run.py']),
    ).toEqual(['app/core.py', 'lib/run.py']);
  });
});

describe('finding the distributions of the analysed files', () => {
  it.each([
    [
      'a root project without a build backend',
      { 'pyproject.toml': '[project]\nname = "x"\n[build-system]\nrequires = []\n' },
      [{ root: '', published: false }],
    ],
    ['a project without a pyproject', {}, []],
    [
      'a published root project',
      { 'pyproject.toml': DISTRIBUTION },
      [{ root: '', published: true }],
    ],
    [
      'a poetry project with the poetry build backend',
      {
        'pyproject.toml':
          '[tool.poetry]\nname = "x"\n[build-system]\nbuild-backend = "poetry.core.masonry.api"\n',
      },
      [{ root: '', published: true }],
    ],
    [
      'a project that classifies itself as private',
      {
        'pyproject.toml':
          '[project]\nname = "x"\nclassifiers = ["Private :: Do Not Upload"]\n[build-system]\nbuild-backend = "hatchling.build"\n',
      },
      [{ root: '', published: false }],
    ],
    [
      'a workspace of a published and an unpublished member',
      {
        'pyproject.toml': '[tool.other]\nx = 1\n',
        'app/pyproject.toml': DISTRIBUTION,
        'tools/pyproject.toml': '[project]\nname = "tools"\n',
      },
      [
        { root: 'app', published: true },
        { root: 'tools', published: false },
      ],
    ],
  ])('reads %s', (_label, manifests, expected) => {
    const projectRoot = project(manifests);

    expect(designDistributions(projectRoot, ['app/core.py', 'tools/run.py', 'main.py'])).toEqual(
      expected,
    );
  });

  it('reads only the folders that hold an analysed file', () => {
    const projectRoot = project({ 'other/pyproject.toml': DISTRIBUTION });

    expect(designDistributions(projectRoot, ['app/core.py'])).toEqual([]);
  });
});
