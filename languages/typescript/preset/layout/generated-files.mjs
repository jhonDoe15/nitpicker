import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { codeExtensionNames, mayBeGenerated } from '../layout.mjs';

const MARKER_LINES = 5;
const GENERATOR_MARKER =
  /@generated\b|\bDO NOT EDIT\b|<auto-generated|\bauto-?generated\b|\bThis file (?:is|was|has been) (?:automatically )?generated\b/iu;
const CODE_FILE = new RegExp(`\\.(?:${codeExtensionNames.join('|')})$`, 'u');

export function hasGeneratorMarker(text) {
  return GENERATOR_MARKER.test(text.split('\n', MARKER_LINES).join('\n'));
}

function projectFiles(projectRoot) {
  const listed = spawnSync(
    'git',
    ['ls-files', '-z', '--cached', '--others', '--exclude-standard'],
    {
      cwd: projectRoot,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    },
  );
  return listed.status === 0 ? listed.stdout.split('\0').filter(Boolean) : [];
}

export function markedGeneratedFiles(projectRoot) {
  return projectFiles(projectRoot).filter((file) => {
    const absolute = path.join(projectRoot, file);
    return (
      CODE_FILE.test(file) &&
      mayBeGenerated(file) &&
      existsSync(absolute) &&
      hasGeneratorMarker(readFileSync(absolute, 'utf8'))
    );
  });
}
