ruleTester.run('no-accumulator-spread-in-reduce', accumulatorSpread, {
  valid: cases([
    'items.reduce((sum, item) => sum + item.price, 0);',
    'items.reduce((acc, item) => ({ ...item, total: acc.total }), start);',
    'const copy = { ...state };',
    'const all = [...left, ...right];',
    'items.reduce((acc, item) => [...item.tags, ...acc.slice(1)], []);',
    'items.reduce(combine, {});',
    'items.map((acc) => ({ ...acc }));',
    'const all = []; for (const item of items) { all.push(item.id); }',
    'let all = []; all = [...all, first];',
    'for (const item of items) { let row = []; row = [...row, item]; use(row); }',
    'let all = []; for (const item of items) { all = [...other, item]; }',
    'let all = []; for (const item of items) { all = [...all.slice(1)]; }',
    'let total = 0; for (const item of items) { total = total + item.price; }',
    'let all = []; for (const item of items) { all = other.concat(item); }',
    'let all = []; function add(item) { all = [...all, item]; } for (const item of items) { add(item); }',
    'let all = []; for (const item of items) { all += [...all, item]; }',
    "let text = ''; for (const part of parts) { text = text.concat(part); }",
    "items.reduce((text, item) => text.concat(item.name), '');",
  ]),
  invalid: [
    ...[
      'items.reduce((acc, item) => ({ ...acc, [item.id]: item }), {});',
      'items.reduce((acc, item) => [...acc, item.id], []);',
      'items.reduceRight((acc, item) => [item.id, ...acc], []);',
      'items.reduce(function (map, item) { return { ...map, [item.id]: item }; }, {});',
      'items.reduce((acc, item) => { acc.total += 1; return { ...acc, last: item }; }, {});',
    ].map((code) => ({ code, errors: [{ messageId: 'spread' }] })),
    ...[
      'let all = []; for (const item of items) { all = [...all, item]; }',
      'let all = []; for (const item of items) { all = [item.id, ...all]; }',
      'let all = []; for (const item of items) { all = all.concat(item.tags); }',
      'let all = []; items.forEach((item) => { all = [...all, item]; });',
      'let all = []; let i = 0; while (i < items.length) { all = [...all, items[i]]; i += 1; }',
      'let all = []; for (const group of groups) { for (const item of group) { all = [...all, item]; } }',
    ].map((code) => ({ code, errors: [{ messageId: 'loopCopy', data: { name: 'all' } }] })),
    ...[
      'items.reduce((acc, item) => acc.concat([item.id]), []);',
      'items.reduceRight(function (all, item) { return all.concat(item.tags); }, []);',
    ].map((code) => ({ code, errors: [{ messageId: 'concat' }] })),
    {
      code: 'let byId = {}; for (const item of items) { byId = { ...byId, [item.id]: item }; }',
      errors: [{ messageId: 'loopCopy', data: { name: 'byId' } }],
    },
  ],
});
