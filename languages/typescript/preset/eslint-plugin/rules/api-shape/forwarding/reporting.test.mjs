import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { expect, it } from 'vitest';
import { Linter } from 'eslint';
import ts from 'typescript';
import tseslint from 'typescript-eslint';
import { createTypedCases } from './test-support/typed-cases.mjs';
import { rule } from '../no-forwarding-wrapper.mjs';
import { normalizeEslintResults } from '../../../../../adapters/eslint/normalize.mjs';
import { compareFindings } from '../../../../../../../core/diff/comparison/compare.mjs';
import { isMarkedGenerated } from '../../../../layout/generated-files.mjs';
import { resolveLayout } from '../../../../layout.mjs';

const { typed, javascriptCase } = createTypedCases();

const sources = [
  [
    'typescript',
    typed,
    'class Prices { subtotal(value: number): number { return value + 1; } total(value: number): number { return this.subtotal(value); } }',
  ],
  [
    'javascript',
    javascriptCase,
    'class Prices {\n/** @param {number} value */\nsubtotal(value) { return value + 1; }\n/** @param {number} value */\ntotal(value) { return this.subtotal(value); }\n}',
  ],
];

function rootOf(fixture) {
  return path.dirname(path.dirname(fixture.filename));
}

function findings(source, fixture) {
  writeFileSync(fixture.filename, source);
  const root = rootOf(fixture);
  const program = ts.createProgram([fixture.filename], {
    strict: true,
    allowJs: true,
    checkJs: true,
    noEmit: true,
    target: ts.ScriptTarget.ES2022,
    types: [],
  });
  const messages = new Linter({ cwd: root }).verify(
    source,
    [
      {
        files: ['**/*.{ts,js}'],
        languageOptions: { parser: tseslint.parser, parserOptions: { programs: [program] } },
        plugins: { nitpicker: { rules: { 'no-forwarding-wrapper': rule } } },
        rules: { 'nitpicker/no-forwarding-wrapper': 'error' },
      },
    ],
    { filename: fixture.filename },
  );
  return normalizeEslintResults({
    value: [{ filePath: fixture.filename, messages }],
    projectRoot: root,
    analyzerName: 'eslint-lint',
  });
}

it.each(sources)(
  'keeps actual %s findings stable across inserted lines',
  (_name, writeCase, source) => {
    const fixture = writeCase(source);
    const baseFindings = findings(source, fixture);
    const headFindings = findings(`\n\n${source}`, fixture);

    expect(baseFindings.map(({ rule: id }) => id)).toEqual(['nitpicker/no-forwarding-wrapper']);
    expect(compareFindings({ baseFindings, headFindings }).newFindings).toEqual([]);
    expect(headFindings[0].location.line).toBe(baseFindings[0].location.line + 2);
  },
);

it.each(sources)(
  'excludes a generated %s alias file from the real layout input selection',
  (name, writeCase, source) => {
    const fixture = writeCase(`// Code generated by protoc-gen-ts. DO NOT EDIT.\n${source}`);
    const root = rootOf(fixture);
    const file = path.relative(root, fixture.filename);
    const marked = isMarkedGenerated(root, file);
    const layout = resolveLayout({}, [], {
      javascript: name === 'javascript',
      generatedFiles: marked ? [file] : [],
    });

    expect(marked).toBe(true);
    expect(layout.projectCodeFiles(root).includes(file)).toBe(false);
  },
);
