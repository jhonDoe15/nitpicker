let findings;

beforeAll(() => {
  findings = analyzeFiles({
    ...LIBRARY,
    ...DYNAMIC,
    ...CALLBACK,
    ...DECLARED,
    ...REFS,
    ...NAMESPACE,
    ...CLONED,
    ...DEFAULTS,
    ...LOADED,
    ...STORIES,
    ...CALLERS,
    ...GENERIC,
    ...SHARED,
  });
});

describe('props and options whose callers a plain reference scan would miss', () => {
  it('leaves a component alone when a value reference lets a library supply its props', () => {
    expect(findingsIn(findings, 'src/library')).toEqual([
      'unused-prop src/library/parts.tsx Rendered.b',
    ]);
  });

  it('follows createElement, treats non-literal props as all and leaves loaded modules alone', () => {
    expect(findingsIn(findings, 'src/dynamic')).toEqual([
      'unused-prop src/dynamic/direct.tsx Direct.b',
    ]);
  });

  it('counts a conditionally passed callback as passed and ignores how the component calls it', () => {
    expect(findingsIn(findings, 'src/callback')).toEqual([
      'unused-prop src/callback/dialog.tsx Dialog.onOpen',
    ]);
  });

  it('skips generated files and members from declaration files and libraries', () => {
    expect(findingsIn(findings, 'src/declared')).toEqual([
      'unused-prop src/declared/mixed.tsx Mixed.own',
    ]);
  });

  it('does not count the ref of a forwardRef component as a prop', () => {
    expect(findingsIn(findings, 'src/refs')).toEqual([]);
  });

  it('leaves every export of a namespace that is used as a value alone', () => {
    expect(findingsIn(findings, 'src/namespace')).toEqual([]);
  });

  it('counts props that cloneElement sets as passed', () => {
    expect(findingsIn(findings, 'src/cloned')).toEqual([
      'unused-prop src/cloned/parts.tsx Cloned.label',
    ]);
  });

  it('counts defaultProps keys as passed', () => {
    expect(findingsIn(findings, 'src/defaults')).toEqual([
      'unused-prop src/defaults/parts.tsx WithDefaults.c',
    ]);
  });

  it('leaves modules a template-literal import or import.meta.glob may load alone', () => {
    expect(findingsIn(findings, 'src/loaded')).toEqual([
      'unused-prop src/loaded/kept/note.tsx Note.extra',
    ]);
  });

  it('treats a production folder named stories as production and a story file as support', () => {
    expect(findingsIn(findings, 'src/stories')).toEqual([
      'unused-prop src/stories/ui/avatar.tsx Avatar.badge',
    ]);
  });

  it('counts JavaScript callers, root config files and scripts as callers', () => {
    expect(findingsIn(findings, 'src/callers')).toEqual([
      'unused-option src/callers/build.ts bundle.watch',
      'unused-prop src/callers/dyn.tsx Dyn.c',
    ]);
  });

  it('does not judge props typed by a type parameter', () => {
    expect(findingsIn(findings, 'src/generic')).toEqual([]);
  });

  it('does not judge a props type that several components share', () => {
    expect(findingsIn(findings, 'src/shared')).toEqual([]);
  });
});

describe('cloneElement with props it cannot read', () => {
  it('treats every component as receiving every prop', () => {
    expect(
      analyzeFiles({
        ...DEFAULTS,
        'src/host.tsx': `import { cloneElement, type ReactElement } from 'react';
export const Host = ({ el, extra }: { el: ReactElement; extra: object }) => cloneElement(el, extra);
`,
      }),
    ).toEqual([]);
  });
});
