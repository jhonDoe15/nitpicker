//! AutoValueSubclassLeaked: a use of an `AutoValue_` class outside the file with the `@AutoValue` base class.
use super::Context;
use super::inject_checks::{annotation_class, annotations_of};
use crate::engine::source::{children, parent, walk};
use crate::java::types::scope::enclosing_type;
use tree_sitter::Node;

const AUTO_VALUE: &str = "com.google.auto.value.AutoValue";
const CLASSES: [&str; 5] = ["class_declaration", "interface_declaration", "enum_declaration", "record_declaration", "annotation_type_declaration"];
const DECLARATIONS: [&str; 10] = [
    "class_declaration", "interface_declaration", "enum_declaration", "record_declaration", "annotation_type_declaration", "constructor_declaration", "method_declaration",
    "variable_declarator", "formal_parameter", "method_invocation",
];

/// `\$*AutoValue_.*` on a simple name.
fn auto_value_name(name: &str) -> bool {
    name.trim_start_matches('$').starts_with("AutoValue_")
}

fn simple_name(text: &str) -> &str {
    text.rsplit('.').next().unwrap_or(text).trim()
}

fn generated(context: &Context, class: Node) -> bool {
    annotations_of(class).into_iter().any(|annotation| annotation.child_by_field_name("name").is_some_and(|name| simple_name(context.text(name)) == "Generated"))
}

fn in_generated_class(context: &Context, node: Node) -> bool {
    let mut current = parent(node);
    while let Some(at) = current {
        if CLASSES.contains(&at.kind()) && generated(context, at) {
            return true;
        }
        current = parent(at);
    }
    false
}

fn has_auto_value(context: &Context, class: &str) -> bool {
    context.resolver.index.get(class).is_some_and(|info| info.class_annotations.iter().any(|full| full == AUTO_VALUE))
}

/// The `@AutoValue` classes of this file, and the ones the `AutoValue_` classes of this file extend.
fn auto_value_classes(context: &Context) -> Vec<String> {
    let mut found: Vec<String> = Vec::new();
    walk(context.file.tree.root_node(), |node| {
        if !CLASSES.contains(&node.kind()) {
            return;
        }
        let Some(name) = enclosing_type(context.file, context.resolver.scope, node) else { return };
        if annotations_of(node).into_iter().any(|annotation| annotation_class(context, annotation).as_deref() == Some(AUTO_VALUE)) {
            found.push(name.clone());
        }
        if node.child_by_field_name("name").is_some_and(|written| auto_value_name(context.text(written))) {
            let index = context.resolver.index;
            let mut above = Some(name);
            while let Some(current) = above {
                if has_auto_value(context, &current) {
                    found.push(current);
                    break;
                }
                above = index.get(&current).and_then(|info| info.superclass.clone());
            }
        }
    });
    found
}

fn last_dot(node: Node) -> Option<usize> {
    children(node).into_iter().rev().find(|part| !part.is_named() && part.kind() == ".").map(|dot| dot.start_byte())
}

fn name_of<'t>(node: Node<'t>) -> Option<Node<'t>> {
    match node.kind() {
        "identifier" | "type_identifier" => Some(node),
        "field_access" => node.child_by_field_name("field"),
        "scoped_type_identifier" => children(node).into_iter().rev().find(|part| part.kind() == "type_identifier"),
        "scoped_identifier" => node.child_by_field_name("name"),
        _ => None,
    }
}

pub fn auto_value_subclass_leaked(context: &Context, node: Node) {
    let Some(name) = name_of(node) else { return };
    let written = context.text(name);
    if !auto_value_name(written) {
        return;
    }
    let qualified = node.kind() != "identifier" && node.kind() != "type_identifier";
    if !qualified && parent(node).is_some_and(|up| DECLARATIONS.contains(&up.kind()) && up.child_by_field_name("name") == Some(node)) {
        return;
    }
    if !qualified && context.resolver.is_variable(node, written) {
        return;
    }
    let text: String = context.text(node).split_whitespace().collect();
    if qualified && node.kind() == "field_access" && node.child_by_field_name("object").is_some_and(|object| matches!(object.kind(), "identifier") && context.resolver.is_variable(node, context.text(object))) {
        return;
    }
    let Some(symbol) = context.resolver.class_name(node, &text) else { return };
    if simple_name(&symbol) != written || in_generated_class(context, node) {
        return;
    }
    let index = context.resolver.index;
    if auto_value_classes(context).iter().any(|av| *av == symbol || index.is_subtype(&symbol, av)) {
        return;
    }
    let at = if qualified { last_dot(node).unwrap_or(node.start_byte()) } else { node.start_byte() };
    let message = "Do not refer to the autogenerated AutoValue_ class outside the file containing the corresponding @AutoValue base class.";
    for _ in 0..if anonymous_type(node) { 2 } else { 1 } {
        context.report_fixed("AutoValueSubclassLeaked", node, at, message, &[]);
    }
}

/// javac shares the written class of `new C() {}` between the creation and the anonymous class, so a scan visits it twice.
fn anonymous_type(node: Node) -> bool {
    let mut current = node;
    while let Some(up) = parent(current) {
        match up.kind() {
            "scoped_type_identifier" | "generic_type" | "annotated_type" => current = up,
            "object_creation_expression" => return up.child_by_field_name("type") == Some(current) && children(up).into_iter().any(|part| part.kind() == "class_body"),
            _ => return false,
        }
    }
    false
}
