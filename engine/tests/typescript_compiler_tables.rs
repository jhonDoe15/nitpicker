//! The numbers the TypeScript compiler's API server uses for syntax kinds and flags differ from the JavaScript
//! API's and may change between compiler versions. `src/typescript/types/tables.rs` is generated from the
//! enum files of the compiler package; this test fails when the installed package no longer matches it.
//! `NITPICKER_ENGINE_WRITE_TABLES=1 cargo test --test typescript_compiler_tables` writes the file again.
use std::fmt::Write;
use std::path::{Path, PathBuf};

const TABLES: &[(&str, &str, &str)] = &[
    ("syntaxKind", "SyntaxKind", "kind"),
    ("typeFlags", "TypeFlags", "type_flags"),
    ("objectFlags", "ObjectFlags", "object_flags"),
    ("symbolFlags", "SymbolFlags", "symbol_flags"),
    ("modifierFlags", "ModifierFlags", "modifier_flags"),
    ("nodeFlags", "NodeFlags", "node_flags"),
    ("signatureKind", "SignatureKind", "signature_kind"),
    ("signatureFlags", "SignatureFlags", "signature_flags"),
    ("elementFlags", "ElementFlags", "element_flags"),
];

fn package() -> Option<PathBuf> {
    let named = std::env::var_os("NITPICKER_TYPESCRIPT_PACKAGE").map(PathBuf::from);
    let installed = Path::new(env!("CARGO_MANIFEST_DIR")).join("../node_modules/@typescript/native");
    named.or(Some(installed)).filter(|folder| folder.join("dist/enums").is_dir())
}

fn constant(name: &str) -> String {
    let letters: Vec<char> = name.chars().collect();
    let mut out = String::new();
    for (at, letter) in letters.iter().enumerate() {
        let before = at.checked_sub(1).map(|index| letters[index]);
        let after = letters.get(at + 1);
        let starts_word = letter.is_ascii_uppercase()
            && before.is_some_and(|before| {
                before.is_ascii_lowercase() || before.is_ascii_digit() || (before.is_ascii_uppercase() && after.is_some_and(char::is_ascii_lowercase))
            });
        if starts_word {
            out.push('_');
        }
        out.push(letter.to_ascii_uppercase());
    }
    out
}

/// `Enum[Enum["Name"] = 12] = "Name";` lines, in file order.
fn members(text: &str, name: &str) -> Vec<(String, i64)> {
    let opening = format!("{name}[{name}[\"");
    text.lines()
        .filter_map(|line| {
            let rest = line.trim().strip_prefix(&opening)?;
            let (member, rest) = rest.split_once("\"] = ")?;
            let (value, _) = rest.split_once(']')?;
            Some((member.to_string(), value.parse().ok()?))
        })
        .collect()
}

fn generate(package: &Path) -> String {
    let manifest: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(package.join("package.json")).expect("manifest")).expect("json");
    let version = manifest["version"].as_str().expect("version");
    let mut out = String::new();
    writeln!(out, "//! Syntax kinds and flags as the TypeScript compiler's API server numbers them.").unwrap();
    writeln!(out, "//! Generated by `tests/typescript_compiler_tables.rs` from the enum files of the compiler package. Do not edit.").unwrap();
    writeln!(out, "#![allow(dead_code)]").unwrap();
    writeln!(out, "\n/// The compiler version these numbers were read from.").unwrap();
    writeln!(out, "pub const GENERATED_FROM: &str = \"{version}\";").unwrap();
    for (file, name, module) in TABLES {
        let text = std::fs::read_to_string(package.join("dist/enums").join(format!("{file}.enum.js"))).expect("enum file");
        let members = members(&text, name);
        assert!(!members.is_empty(), "{file} has no members");
        writeln!(out, "\npub mod {module} {{").unwrap();
        for (member, value) in &members {
            writeln!(out, "    pub const {}: u32 = {};", constant(member), *value as u32).unwrap();
        }
        if *module == "kind" {
            writeln!(out, "\n    /// The first name of each kind, for messages.").unwrap();
            writeln!(out, "    pub fn name(kind: u32) -> &'static str {{").unwrap();
            writeln!(out, "        match kind {{").unwrap();
            let mut seen = std::collections::HashSet::new();
            for (member, value) in &members {
                if seen.insert(*value) {
                    writeln!(out, "            {value} => \"{member}\",").unwrap();
                }
            }
            writeln!(out, "            _ => \"?\",").unwrap();
            writeln!(out, "        }}\n    }}").unwrap();
        }
        writeln!(out, "}}").unwrap();
    }
    out.push_str(&shapes(package));
    out
}

/// `[SyntaxKind.Name]: ["first", "second"],` lines of the node encoder: the child properties of each kind, in
/// the order of the bits of a node's child mask.
fn shapes(package: &Path) -> String {
    let text = std::fs::read_to_string(package.join("dist/api/node/protocol.generated.js")).expect("encoder table");
    let kinds = std::fs::read_to_string(package.join("dist/enums/syntaxKind.enum.js")).expect("enum file");
    let numbers: std::collections::HashMap<String, i64> = members(&kinds, "SyntaxKind").into_iter().collect();
    let table = text.split("export const childProperties = {").nth(1).and_then(|rest| rest.split("\n};").next()).expect("childProperties");
    let mut out = String::new();
    writeln!(out, "\npub mod shape {{").unwrap();
    writeln!(out, "    /// Names of the child properties of a kind; bit `n` of a node's child mask says whether property `n` is present.").unwrap();
    writeln!(out, "    pub fn child_properties(kind: u32) -> &'static [&'static str] {{").unwrap();
    writeln!(out, "        match kind {{").unwrap();
    let mut count = 0;
    for line in table.lines() {
        let Some(rest) = line.trim().strip_prefix("[SyntaxKind.") else { continue };
        let (name, rest) = rest.split_once("]: [").expect("entry");
        let names = rest.trim_end_matches(',').trim_end_matches(']');
        writeln!(out, "            {} => &[{names}],", numbers[name]).unwrap();
        count += 1;
    }
    assert!(count > 100, "only {count} shapes");
    writeln!(out, "            _ => &[],").unwrap();
    writeln!(out, "        }}\n    }}\n}}").unwrap();
    out
}

#[test]
fn tables_match_the_installed_compiler_package() {
    let Some(package) = package() else {
        eprintln!("no TypeScript 7 package installed; tables not compared");
        return;
    };
    let generated = generate(&package);
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/typescript/types/tables.rs");
    if std::env::var_os("NITPICKER_ENGINE_WRITE_TABLES").is_some() {
        std::fs::write(&path, &generated).expect("write");
    }
    let stored = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(stored == generated, "{} is out of date for this compiler package; see the top of this test", path.display());
}

#[test]
fn names_become_constants() {
    assert_eq!(constant("Identifier"), "IDENTIFIER");
    assert_eq!(constant("JSDocTag"), "JS_DOC_TAG");
    assert_eq!(constant("ES2015"), "ES2015");
    assert_eq!(constant("JsxText"), "JSX_TEXT");
    assert_eq!(constant("NoSubstitutionTemplateLiteral"), "NO_SUBSTITUTION_TEMPLATE_LITERAL");
}
