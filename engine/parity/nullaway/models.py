"""Writes src/java/errorprone/nullaway_models.rs from NullAway's default library models (LibraryModelsHandler.java, MIT)."""
import re
import sys

text = open(sys.argv[1]).read()
start = text.index("private static class DefaultLibraryModels")
sections = re.split(r"private static final Immutable\w+<[^=]*>\s+(\w+)\s*=", text[start:])
tables = {}
for name, body in zip(sections[1::2], sections[2::2]):
    body = body.split(";\n\n")[0]
    rows = []
    for found in re.finditer(r'methodRef\(\s*"([^"]+)",\s*"([^"]+)"\s*\)(?:\s*,\s*(\d+))?', body):
        owner, signature, index = found.group(1), found.group(2), found.group(3)
        signature = re.sub(r"^<[^>]*>", "", signature)
        method, parameters = signature[:-1].split("(", 1)
        erased = ",".join(re.sub(r"<.*>", "", part).strip() for part in parameters.split(",")) if parameters else ""
        rows.append((owner, method, erased, int(index) if index else 0))
    tables[name] = rows
out = ["//! NullAway's default library models as data. Generated by parity/nullaway/models.py from NullAway 0.14.2", "//! (MIT licence, Copyright (c) 2017 Uber Technologies, Inc.); do not edit by hand.", "", "/// Class, method name, parameter types as NullAway writes them, parameter index (0 where the table has none).", "pub type Model = (&'static str, &'static str, &'static str, usize);", ""]
for name in ["FAIL_IF_NULL_PARAMETERS", "NULL_IMPLIES_TRUE_PARAMETERS", "NULL_IMPLIES_FALSE_PARAMETERS", "NULL_IMPLIES_NULL_PARAMETERS", "ALWAYS_NULLABLE_RETURNS", "NULLABLE_RETURNS_JSPECIFY_MODE_DISABLED", "NONNULL_RETURNS", "CAST_TO_NONNULL_METHODS"]:
    rows = tables[name]
    out.append(f"pub const {name}: &[Model] = &[")
    out.extend(f'    ("{owner}", "{method}", "{parameters}", {index}),' for owner, method, parameters, index in rows)
    out.append("];")
    out.append("")
open(sys.argv[2], "w").write("\n".join(out))
print({name: len(rows) for name, rows in tables.items()})
