import { describe, expect, it } from 'vitest';
import { between } from '../build-files/test-support/policy-fixtures.mjs';

const HEADING = 'generated-file markers added to checked code, which the checks now skip';
const HEADER = '// Code generated by billing-gen. DO NOT EDIT.\n';

function loosenedBy({ config, base, file, marked }) {
  const head = { ...base, [file]: marked };
  return between({ base, head, config }).policyLoosenings;
}

const PRESETS = [
  {
    name: 'Java',
    config: { preset: 'java' },
    build: { 'build.gradle': "plugins { id 'java' }\n" },
    file: 'src/main/java/a/Billing.java',
    text: 'package a;\n\npublic class Billing {\n  int total(int a) { return a * 3; }\n}\n',
    marks: [
      ['a generator header', (text) => `${HEADER}${text}`],
      [
        'a @Generated annotation naming a known generator',
        (text) =>
          text.replace(
            'public class',
            '@javax.annotation.processing.Generated("dagger.x")\npublic class',
          ),
      ],
    ],
  },
  {
    name: 'Kotlin',
    config: { preset: 'kotlin' },
    build: { 'build.gradle.kts': 'plugins { kotlin("jvm") }\n' },
    file: 'src/main/kotlin/a/Billing.kt',
    text: 'package a\n\nclass Billing {\n    fun total(a: Int) = a * 3\n}\n',
    marks: [['a generator header', (text) => `${HEADER}${text}`]],
  },
  {
    name: 'Python',
    config: { preset: 'python' },
    build: {
      'pyproject.toml': '[project]\nname = "app"\nversion = "1"\n',
      'src/app/__init__.py': '',
    },
    file: 'src/app/billing.py',
    text: 'def total(a):\n    return a * 3\n',
    marks: [
      ['a generator header', (text) => `# Code generated by billing-gen. DO NOT EDIT.\n${text}`],
    ],
  },
  {
    name: 'Go',
    config: { preset: 'go' },
    build: { 'go.mod': 'module example.com/app\n\ngo 1.22\n' },
    file: 'billing/billing.go',
    text: 'package billing\n\nfunc Total(a int) int {\n\treturn a * 3\n}\n',
    marks: [['a generator header', (text) => `${HEADER}\n${text}`]],
  },
  {
    name: 'TypeScript',
    config: { preset: 'typescript' },
    build: { 'package.json': '{"name":"app","type":"module"}\n' },
    file: 'src/billing.ts',
    text: 'export function total(a: number): number {\n  return a * 3;\n}\n',
    marks: [['a generator header', (text) => `${HEADER}${text}`]],
  },
];

describe.each(PRESETS)(
  'generated-file markers with $name',
  ({ config, build, file, text, marks }) => {
    const base = { ...build, [file]: text };

    it.each(marks)('counts %s added to a file the base checked', (_, mark) => {
      expect(loosenedBy({ config, base, file, marked: mark(text) })).toEqual([
        `${HEADING}: ${file}`,
      ]);
    });

    it('keeps a generated file this change adds and one the base already marked', () => {
      const [, mark] = marks[0];
      const added = `${file.slice(0, file.lastIndexOf('/'))}/Added${file.slice(file.lastIndexOf('.'))}`;
      const generated = { ...base, [file]: mark(text) };

      expect(
        between({ base, head: { ...base, [added]: mark(text) }, config }).policyLoosenings,
      ).toEqual([]);
      expect(loosenedBy({ config, base: generated, file, marked: `${mark(text)}\n` })).toEqual([]);
    });
  },
);
