describe('config schema and validator on exceptions', () => {
  const entry = { paths: ['src/legacy/**'], reason: 'Legacy module until the migration' };
  const rules = [
    ...new Set([...RULES.map(({ id }) => id), 'exports', 'types', 'pmd/UnusedPrivateField']),
  ];

  it('never rejects an exception that the validator accepts', () => {
    for (const rule of rules) {
      const variants = [{}, { function: 'run' }, { name: 'run' }, { packages: ['left-pad'] }];
      for (const variant of variants) {
        for (const config of everyPreset({ exceptions: [{ rule, ...entry, ...variant }] })) {
          if (validatorAccepts(config)) {
            expect(schemaErrors(config), JSON.stringify(config)).toEqual([]);
          }
        }
      }
    }
  });

  it.each([
    [{ rule: 'file-lines-limit', paths: [], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['/abs/a.ts'], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['C:/a.ts'], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['..\\a.ts'], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['../a.ts'], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: [' '], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['src\\a.ts'], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['src/a.ts'], reason: '...' }],
    [{ rule: 'file-lines-limit', paths: ['src/a.ts'], reason: '  ' }],
    [{ rule: 'file-lines-limit', paths: ['src/a.ts'] }],
    [{ rule: 'file-lines-limit', reason: 'Because' }],
    [{ paths: ['src/a.ts'], reason: 'Because' }],
    [{ rule: 'TS2322', paths: ['src/a.ts'], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['src/a.ts'], reason: 'Because', function: 'run' }],
    [
      {
        rule: 'crap-score-limit',
        paths: ['src/a.ts'],
        reason: 'Because',
        function: 'run',
        name: 'run',
      },
    ],
    [{ rule: 'crap-score-limit', paths: ['src/a.ts'], reason: 'Because', function: ' ' }],
    [{ rule: 'changed-branch-coverage', paths: ['src/a.ts'], reason: 'Because' }],
    [{ rule: 'exports', paths: ['src/a.ts'], reason: 'Because', name: 'run' }],
    [{ rule: 'exports', paths: ['src/a.ts'], reason: 'Because', function: 'run' }],
    [{ rule: 'file-lines-limit', paths: ['src/a.ts'], reason: 'Because', packages: ['x'] }],
    [{ rule: 'unused-dependency', paths: ['package.json'], reason: 'Because', packages: [] }],
    [{ rule: 'unused-dependency', paths: ['package.json'], reason: 'Because', packages: ['x'] }],
    [{ rule: 'file-lines-limit', paths: ['./src/a.ts'], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['src/'], reason: 'Because' }],
    [{ rule: 'formatjs/enforce-id', paths: ['src/a.ts'], reason: 'Because' }],
    [{ rule: 'formatjs/enforce-description', paths: ['src/a.ts'], reason: 'Because' }],
    [{ rule: 'doc-comment-content', paths: ['src/a.ts'], reason: 'Because' }],
    [{ rule: 'file-lines-limit', paths: ['a.ts'], reason: 'Because', extra: true }],
  ])('on %j with every preset', (exception) => {
    for (const config of everyPreset({ exceptions: [exception] })) {
      expectAgreement(config);
    }
  });

  it('never rejects a python.exceptions entry that the validator accepts', () => {
    const ids = [
      'ruff',
      'E501',
      'S101',
      'reportMissingImports',
      'swallowed-exception',
      'attr-defined',
    ];
    for (const rule of ids) {
      const config = { preset: 'python', python: { exceptions: [{ rule, ...entry }] } };
      if (validatorAccepts(config)) {
        expect(schemaErrors(config), rule).toEqual([]);
      }
    }
    expectAgreement({
      preset: 'python',
      python: { exceptions: [{ rule: 'file-lines-limit', ...entry }] },
    });
    expectAgreement({
      preset: 'python',
      python: {
        exceptions: [{ rule: 'swallowed-exception', paths: ['./a.py'], reason: 'Because' }],
      },
    });
  });
});
